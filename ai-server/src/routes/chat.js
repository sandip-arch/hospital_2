const express = require("express");

const router = express.Router();

const {
    verifyInternalRequest
} = require("../middleware/internal-auth");

const {
    generateAIResponse
} = require("../services/groq.service");

const {
    SYSTEM_PROMPT
} = require("../prompts/system.prompt");

// ========================================
// POST /api/chat
// Internal Laravel → Node endpoint
// ========================================

router.post("/", verifyInternalRequest, async (req, res) => {

    try {

        // ========================================
        // 1. Get request data
        // ========================================

        const {
            message,
            user
        } = req.body;

        // ========================================
        // 2. Validate message
        // ========================================

        if (!message || typeof message !== "string") {

            return res.status(400).json({
                success: false,
                error: "Message is required."
            });

        }

        const userMessage = message.trim();

        if (userMessage.length === 0) {

            return res.status(400).json({
                success: false,
                error: "Message cannot be empty."
            });

        }

        // ========================================
        // 3. Validate trusted user context
        // ========================================

        if (!user || !user.userId) {

            return res.status(400).json({
                success: false,
                error: "User context is required."
            });

        }

        if (!Array.isArray(user.roles)) {

            return res.status(400).json({
                success: false,
                error: "User roles are required."
            });

        }

        if (user.roles.length === 0) {

            return res.status(403).json({
                success: false,
                error: "User has no assigned role."
            });

        }

        if (
            user.profileType !== null &&
            typeof user.profileType !== "string"
        ) {

            return res.status(400).json({
                success: false,
                error: "Invalid profile type."
            });

        }

        // ========================================
        // 4. Normalize roles
        // ========================================

        const normalizedRoles = user.roles
            .map(role => String(role).trim().toLowerCase())
            .filter(Boolean);

        // ========================================
        // 5. Build trusted AI context
        // ========================================

        const contextMessage = `
Authenticated CMS user context:

User ID: ${user.userId}

Roles:
${Array.isArray(user.roles) ? user.roles.join(", ") : "Unknown"}

Profile Type: ${user.profileType || "Unknown"}

Profile ID: ${user.profileId || "Unknown"}

LIVE AUTHORIZED APPLICATION DATA:

${JSON.stringify(user.liveContext || {}, null, 2)}

IMPORTANT:

The live application data above was generated by Laravel.

Laravel is the authority for authorization.

Do not assume access to information that is not present
in the provided live context.

Do not invent database records.

Do not infer private information that is not explicitly provided.
`;

        // ========================================
        // 6. Send to Groq
        // ========================================

        const answer = await generateAIResponse([
            {
                role: "system",
                content: SYSTEM_PROMPT
            },
            {
                role: "system",
                content: contextMessage
            },
            {
                role: "user",
                content: userMessage
            }
        ]);

        // ========================================
        // 7. Return response
        // ========================================

        return res.status(200).json({
            success: true,
            answer
        });

    } catch (error) {

        console.error("========================================");
        console.error("AI CHAT ERROR");
        console.error(error);
        console.error("========================================");

        return res.status(500).json({
            success: false,
            error: "AI service temporarily unavailable."
        });
    }
});

module.exports = router;